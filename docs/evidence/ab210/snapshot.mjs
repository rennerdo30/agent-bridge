import { DatabaseSync, backup } from 'node:sqlite';
import { copyFileSync, existsSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source='C:/Users/renne/.agent-bridge/bridge.db';
const dest='D:/Development/ab210-copy/bridge.db';
if(existsSync(dest)) throw new Error('Refusing to overwrite copy');
const db=new DatabaseSync(source,{timeout:2000});
db.exec('PRAGMA busy_timeout=2000');
const start=Date.now();
const checkpoint=db.prepare('PRAGMA wal_checkpoint(TRUNCATE)').get();
console.log(JSON.stringify({checkpoint}));
db.exec('BEGIN');
db.prepare('SELECT count(*) FROM sqlite_master').get();
const wal=source+'-wal';
const method=Number(checkpoint.busy)===0 && (!existsSync(wal)||statSync(wal).size===0)?'read-pinned-copyFile':'sqlite-backup';
if(method==='read-pinned-copyFile') copyFileSync(source,dest);
else await backup(db,dest);
db.exec('ROLLBACK'); db.close();
const copy=new DatabaseSync(dest,{readOnly:true});
const check=copy.prepare('PRAGMA quick_check').all();
const schema=copy.prepare("SELECT name,type,sql FROM sqlite_master WHERE type IN ('table','index')").all();
copy.close();
const result={method,checkpoint,seconds:(Date.now()-start)/1000,bytes:statSync(dest).size,check,schema};
writeFileSync('D:/Development/ab210-copy/snapshot.json',JSON.stringify(result,null,2));
console.log(JSON.stringify({...result,schema:undefined}));
if(check.length!==1||check[0].quick_check!=='ok') throw new Error('Copy failed quick_check');
