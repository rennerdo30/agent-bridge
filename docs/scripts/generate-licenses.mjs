// Writes the "Licenses and trademarks" page from the licenses of the code and fonts the website
// ships (Astro and Starlight runtime scripts, search, code blocks, the theme's fonts). The page is
// generated at build time, so its versions and texts always match the installed packages.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SHIPPED = [
  "astro",
  "@astrojs/starlight",
  "starlight-theme-galaxy",
  "astro-expressive-code",
  "pagefind",
  "@fontsource-variable/inter",
  "@fontsource-variable/jetbrains-mono",
];
// Expressive Code ships its core and plugins as separate packages.
const scoped = existsSync("node_modules/@expressive-code") ? readdirSync("node_modules/@expressive-code").map((p) => `@expressive-code/${p}`) : [];

const entries = [...SHIPPED, ...scoped].map((name) => {
  const dir = join("node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const entry = readdirSync(dir, { withFileTypes: true }).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f.name));
  if (!entry) throw new Error(`generate-licenses: ${name} has no license file`);
  // Some packages (pagefind) ship a LICENSE folder with one file per bundled component.
  const path = join(dir, entry.name);
  const files = entry.isDirectory() ? readdirSync(path).sort().map((f) => join(path, f)) : [path];
  const text = files.map((f) => readFileSync(f, "utf8").trim()).join("\n\n");
  return { name, version: pkg.version, license: pkg.license, text };
});

const page = [
  "---",
  "title: Licenses and trademarks",
  "description: The licenses of agent-bridge, the third-party software it ships, and trademark notes.",
  "---",
  "",
  "<!-- Generated by scripts/generate-licenses.mjs at build time. Do not edit. -->",
  "",
  "## agent-bridge",
  "",
  "agent-bridge is free software under the [MIT license](https://github.com/rennerdo30/agent-bridge/blob/main/LICENSE), copyright (c) 2026 rennerdo30.",
  "",
  "The plugin bundles include third-party libraries such as the Model Context Protocol SDK, zod and @peculiar/x509. Their licenses are listed in",
  "[THIRD_PARTY_NOTICES.md](https://github.com/rennerdo30/agent-bridge/blob/main/THIRD_PARTY_NOTICES.md), and from the next release on also in `dist/THIRD_PARTY_NOTICES.md` inside every installed plugin.",
  "",
  "## Trademarks",
  "",
  "Claude Code (Anthropic), OpenAI Codex (OpenAI), Google Antigravity (Google), opencode, Muse, T3 Code, GitHub and all other product and company names are trademarks or names of their respective owners.",
  "They are named only to describe which tools agent-bridge works with. agent-bridge is an independent open-source project and is not affiliated with, endorsed by or sponsored by any of them.",
  "",
  "## This website",
  "",
  "This website is built with the following software and fonts, which are included in the pages you load.",
  "",
  "| Component | Version | License |",
  "| --- | --- | --- |",
  ...entries.map((e) => `| ${e.name} | ${e.version} | ${e.license} |`),
  "",
  ...entries.flatMap((e) => [`### ${e.name} ${e.version}`, "", "```text", e.text, "```", ""]),
].join("\n");

writeFileSync("src/content/docs/licenses.md", page.replace(/\r\n?/g, "\n"));
console.log(`wrote src/content/docs/licenses.md (${entries.length} components)`);
